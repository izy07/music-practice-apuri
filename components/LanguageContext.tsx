const LanguageContext = createContext<LanguageContextType | undefined>(undefined);

export const LanguageProvider: React.FC<{ children?: React.ReactNode }> = ({ children }) => {
  const [language, setLanguageState] = useState<Language>('ja');

  useEffect(() => {
    loadLanguage();
  }, []);

  const loadLanguage = async () => {
    try {
      // まずAsyncStorageから読み込む（高速）
      const savedLanguage = await AsyncStorage.getItem('app_language');
      if (savedLanguage && (savedLanguage === 'ja' || savedLanguage === 'en')) {
        setLanguageState(savedLanguage);
      }

      // データベースから言語設定を読み込む（認証済みユーザーの場合）
      try {
        const { data: { user } } = await supabase.auth.getUser();
        if (user) {
          const result = await getLanguageSetting(user.id);
          if (result.data && (result.data === 'ja' || result.data === 'en')) {
            // データベースの設定を優先
            setLanguageState(result.data);
            // AsyncStorageも更新
            await AsyncStorage.setItem('app_language', result.data);
          }
        }
      } catch (dbError) {
        // データベース読み込みエラーは無視（AsyncStorageの値を使用）
        console.warn('データベースから言語設定を読み込めませんでした:', dbError);
      }
    } catch (error) {
      // デフォルト言語を使用
      console.warn('言語設定の読み込みエラー:', error);
    }
  };

  const setLanguage = async (lang: Language) => {
    try {
      await AsyncStorage.setItem('app_language', lang);
      setLanguageState(lang);
    } catch (error) {
      // 言語保存エラー
    }
  };

  const t = (key: keyof typeof translations.ja): string => {
    return translations[language][key] || key;
  };

  return (
    <LanguageContext.Provider value={{ language, setLanguage, t }}>
      {children}
    </LanguageContext.Provider>
  );
};

export const useLanguage = () => {
  const context = useContext(LanguageContext);
  if (context === undefined) {
    throw new Error('useLanguage must be used within a LanguageProvider');
  }
  return context;
};